#!/usr/bin/env python3
"""Embeds the UI font (third_party/fonts/inter, Latin subset, SIL OFL) into src/app/font_inter.inc."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'third_party', 'fonts', 'inter')
out = ['// GENERATED by tools/embed_fonts.py. Inter (SIL Open Font License 1.1), see third_party/fonts/inter/OFL.txt.']
for name, var in (('Inter-Regular.otf', 'INTER_REGULAR'), ('Inter-SemiBold.otf', 'INTER_SEMIBOLD')):
    data = open(os.path.join(SRC, name), 'rb').read()
    out.append(f'static const unsigned char {var}[{len(data)}] = {{')
    for i in range(0, len(data), 24):
        out.append('  ' + ','.join(str(b) for b in data[i:i + 24]) + ',')
    out.append('};')
open(os.path.join(HERE, '..', 'src', 'app', 'font_inter.inc'), 'w').write('\n'.join(out) + '\n')
print('wrote src/app/font_inter.inc')

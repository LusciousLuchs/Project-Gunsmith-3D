#!/usr/bin/env python3
"""Embeds the owner's artwork into the game (the .exe carries it, no files beside it):
   assets/logo/oab_foundry.jpg      -> src/ui/logo_oab.inc  OAB_LOGO_JPG      (the studio's launch splash)
   assets/logo/title_splash.jpg     -> src/ui/art.inc       TITLE_SPLASH_JPG  (the game's title splash)
   assets/logo/menu_background.jpg  -> src/ui/art.inc       MENU_BG_JPG       (the main menu's workshop picture)
   assets/logo/gunsmith3d_icon.png  -> src/ui/art.inc       ICON_PNG          (the window's icon)
   assets/logo/menu_logo.png        -> src/ui/art.inc       MENU_LOGO_PNG     (the main menu's logo: the title, faded out)"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')

def arr(name, path):
    data = open(os.path.join(ROOT, path), 'rb').read()
    out = [f'static const unsigned char {name}[{len(data)}] = {{']
    for k in range(0, len(data), 40):
        out.append(','.join(str(b) for b in data[k:k + 40]) + ',')
    out.append('};')
    return out

def write(inc, items):
    out = ['// GENERATED by tools/embed_logo.py from assets/logo. Do not edit.']
    for name, path in items: out += arr(name, path)
    open(os.path.join(ROOT, 'src', 'ui', inc), 'w').write('\n'.join(out) + '\n')
    print('wrote src/ui/' + inc)

write('logo_oab.inc', [('OAB_LOGO_JPG', 'assets/logo/oab_foundry.jpg')])
write('art.inc', [('TITLE_SPLASH_JPG', 'assets/logo/title_splash.jpg'), ('MENU_BG_JPG', 'assets/logo/menu_background.jpg'),
                  ('ICON_PNG', 'assets/logo/gunsmith3d_icon.png'), ('MENU_LOGO_PNG', 'assets/logo/menu_logo.png')])

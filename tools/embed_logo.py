#!/usr/bin/env python3
"""Embeds the studio's logo (assets/logo/oab_foundry.jpg, the owner's) into src/ui/logo_oab.inc for the launch splash."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
data = open(os.path.join(HERE, '..', 'assets', 'logo', 'oab_foundry.jpg'), 'rb').read()
out = ['// GENERATED by tools/embed_logo.py from assets/logo/oab_foundry.jpg. Do not edit.',
       f'static const unsigned char OAB_LOGO_JPG[{len(data)}] = {{']
for k in range(0, len(data), 40):
    out.append(','.join(str(b) for b in data[k:k + 40]) + ',')
out.append('};')
open(os.path.join(HERE, '..', 'src', 'ui', 'logo_oab.inc'), 'w').write('\n'.join(out) + '\n')
print('wrote src/ui/logo_oab.inc')

#!/usr/bin/env python3
"""Embeds the game's defaults, set by the owner in the developer build, into src/core/builtin_defaults.inc:
assets/defaults/maps/<kind>.gsmap (the built-in map for a career property: garage, shack, retail, warehouse; or
"range", the practice range) and assets/defaults/settings.json (what a new player's Settings start at). Stored as byte
arrays (compact JSON): MSVC refuses string literals over 64 KB."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', 'assets', 'defaults')

def arr(name, text):
    data = text.encode('utf-8')
    rows = [', '.join(str(b) for b in data[i:i + 40]) for i in range(0, len(data), 40)]
    return f'static const unsigned char {name}[] = {{\n' + ',\n'.join(rows) + ('\n' if rows else '0') + '};\n'

out = ['// GENERATED by tools/embed_defaults.py from assets/defaults. Do not edit.', '#include <cstddef>']
entries = []
mdir = os.path.join(ROOT, 'maps')
if os.path.isdir(mdir):
    for f in sorted(os.listdir(mdir)):
        if not f.lower().endswith('.gsmap'):
            continue
        kind = os.path.splitext(f)[0]
        text = json.dumps(json.load(open(os.path.join(mdir, f), encoding='utf-8')), separators=(',', ':'))
        var = 'MAP_' + ''.join(c if c.isalnum() else '_' for c in kind)
        out.append(arr(var, text))
        entries.append((kind, var, len(text.encode('utf-8'))))
sp = os.path.join(ROOT, 'settings.json')
stext = json.dumps(json.load(open(sp, encoding='utf-8')), separators=(',', ':')) if os.path.exists(sp) else ''
out.append(arr('SETTINGS_DEFAULT', stext))
out.append('struct BuiltinDefault { const char* kind; const unsigned char* data; size_t size; };')
out.append('static const BuiltinDefault BUILTIN_MAPS[] = {')
for kind, var, n in entries:
    out.append(f'    {{"{kind}", {var}, {n}}},')
out.append('    {nullptr, nullptr, 0}};')
out.append(f'static const size_t SETTINGS_DEFAULT_SIZE = {len(stext.encode("utf-8"))};')
open(os.path.join(HERE, '..', 'src', 'core', 'builtin_defaults.inc'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('wrote src/core/builtin_defaults.inc:', [e[0] for e in entries], 'settings' if stext else 'no settings')

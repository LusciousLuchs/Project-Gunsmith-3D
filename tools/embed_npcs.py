#!/usr/bin/env python3
"""Embeds the owner's NPCs (assets/npcs/*.json, saved from the NPC editor) into src/core/builtin_npcs.inc, so they
ship with the game as starting points in the NPC editor's New list."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'assets', 'npcs')
out = ['// GENERATED by tools/embed_npcs.py from assets/npcs/*.json. Do not edit.',
       '// (file name, the NPC as saved by the NPC editor)',
       'static const std::vector<std::pair<std::string, std::string>> BUILTIN_NPCS = {']
for name in sorted(os.listdir(SRC)):
    if not name.lower().endswith('.json'):
        continue
    text = open(os.path.join(SRC, name), encoding='utf-8').read()
    json.loads(text)   # (stops here on a broken file)
    assert ')GSNPC"' not in text
    out.append(f'    {{"{os.path.splitext(name)[0]}", R"GSNPC({text})GSNPC"}},')
out.append('};')
open(os.path.join(HERE, '..', 'src', 'core', 'builtin_npcs.inc'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('wrote src/core/builtin_npcs.inc')

#!/usr/bin/env python3
"""Embeds the built-in sounds (assets/sounds/*.ogg) into src/app/builtin_sounds.inc.

The recordings are the owner's, of their own guns: pistol_* a Thunder .380, rifle_* an AR-15 (5.56), action_* the
Thunder's slide; crack_* is the opening crack of AR-15 shots (high-passed). Cleaned (hiss and rumble out, a little top
end back), then punched up (low shelf, compressor, soft clip, peak -1 dB). The pistol shots are only the first 0.12 s:
the brass catcher clangs after that; the game adds a made-up thump and echo (core/shotsound.cpp synthBoom/synthTail).
See app/audio.cpp for how they are played and core/shotsound.cpp for the mix."""
import glob, os
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'assets', 'sounds')
files = sorted(glob.glob(os.path.join(SRC, '*.ogg')))
out = ['// GENERATED by tools/embed_sounds.py from assets/sounds. Do not edit.']
for i, f in enumerate(files):
    data = open(f, 'rb').read()
    out.append(f'static const unsigned char BUILTIN_SND_{i}[{len(data)}] = {{')
    for k in range(0, len(data), 40):
        out.append(','.join(str(b) for b in data[k:k + 40]) + ',')
    out.append('};')
out.append('struct BuiltinSnd { const char* name; const unsigned char* data; int size; };')
out.append('static const BuiltinSnd BUILTIN_SND[] = {')
for i, f in enumerate(files):
    out.append(f'    {{"{os.path.splitext(os.path.basename(f))[0]}", BUILTIN_SND_{i}, (int)sizeof(BUILTIN_SND_{i})}},')
out.append('};')
open(os.path.join(HERE, '..', 'src', 'app', 'builtin_sounds.inc'), 'w').write('\n'.join(out) + '\n')
print('wrote src/app/builtin_sounds.inc:', len(files), 'sounds')

#!/usr/bin/env python3
"""Embeds the built-in part textures (assets/textures/*.jpg) into src/app/builtin_textures.inc.

The pictures are the owner's: samples of real gun finishes, made seamless (their edges cross-faded so they tile)."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'assets', 'textures')
# file, id (saved in blueprints as "builtin:<id>"), name in the game, a natural size for one repeat (mm)
TEXTURES = [
    ('stained_wood.jpg', 'stained_wood', 'Stained wood', 160),
    ('black_polymer.jpg', 'black_polymer', 'Black polymer (stippled)', 40),
    ('blued_steel.jpg', 'blued_steel', 'Blued steel', 120),
]
out = ['// GENERATED by tools/embed_textures.py from assets/textures. Do not edit.']
for i, (f, _, _, _) in enumerate(TEXTURES):
    data = open(os.path.join(SRC, f), 'rb').read()
    out.append(f'static const unsigned char BUILTIN_TEX_{i}[{len(data)}] = {{')
    for k in range(0, len(data), 40):
        out.append(','.join(str(b) for b in data[k:k + 40]) + ',')
    out.append('};')
out.append('struct BuiltinTex { const char* id; const char* name; double scale; const unsigned char* data; int size; };')
out.append('static const BuiltinTex BUILTIN_TEX[] = {')
for i, (f, tid, name, scale) in enumerate(TEXTURES):
    out.append(f'    {{"{tid}", "{name}", {scale}, BUILTIN_TEX_{i}, (int)sizeof(BUILTIN_TEX_{i})}},')
out.append('};')
open(os.path.join(HERE, '..', 'src', 'app', 'builtin_textures.inc'), 'w').write('\n'.join(out) + '\n')
print('wrote src/app/builtin_textures.inc')
